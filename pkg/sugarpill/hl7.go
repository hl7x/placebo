// Segment returns the named segment, or nil when the message does not carry
// one. A message built for a message type holds only that type's segments, so
// the absent ones have to be distinguishable from the empty ones.
func (msg *HL7Message) Segment(name string) interface{} {

	field := reflect.ValueOf(msg).Elem().FieldByName(name)

	if !field.IsValid() || field.IsNil() {
		return nil
	}

	return field.Interface()
}

// MessageBuilder renders every segment the message carries. Used where the
// message came back from JSON rather than from a message type, so what it
// holds is whatever the person editing it left behind.
func MessageBuilder(msg *HL7Message) string {
	return MessageBuilderFor(msg, SegmentOrder)
}

// MessageBuilderFor renders the segments named in layout, in that order. A
// segment the message does not carry is left out rather than sent empty,
// which is what keeps an order message from arriving with an insurance
// segment stapled to it.
func MessageBuilderFor(msg *HL7Message, layout []string) string {

	segments := []string{}

	for _, name := range layout {
		segment := msg.Segment(name)
		if segment == nil {
			continue
		}

		segments = append(segments, message.CreateHL7(segment, name))
	}

	return strings.Join(segments, message.SegmentSeparator)
}

func LinesFromFile(s string) []string {
	return message.SplitSegments(s)
}

// Remove 'null' segments for easier JSON display
func SanitizeLines(lines string) string {
	split := strings.Split(lines, "\n")

	var newLines []string

	for _, line := range split {
		if !strings.Contains(line, ": null") {
			newLines = append(newLines, line)
		}
	}

	join := strings.Join(newLines, "\n")

	return join
}
